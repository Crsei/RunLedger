/**
 * Anthropic Messages adapter —— 公共入口 facade。
 *
 * S8.3 拆分后实现位于 `anthropic-messages/`:
 * - `sse-decoder.ts`        跨 chunk 的 SSE line decoder;
 * - `event-mapper.ts`       SSE event 过滤/解析 + stop reason 映射;
 * - `client.ts`             client 构造 + auth/header 解析;
 * - `params.ts`             buildParams + cache control/effort 映射;
 * - `message-conversion.ts` message/tool_result 转换 + Claude Code tool 名映射;
 * - `tool-conversion.ts`    tool schema 转换 + fine-grained beta 判定;
 * - `types.ts`              公共选项/compat 类型。
 *
 * 本文件只保留 stream/streamSimple 装配与公共 export,不复制实现;
 * 顶层 adapter export 与 lazy adapter import 路径不变。
 */

